# ---- プロセス木（孤児の検出）-------------------------------------------------------------------------------------------
def process_table() -> dict[int, tuple[int, str]]:
    r = subprocess.run(["powershell", "-NoProfile", "-Command",
                        "Get-CimInstance Win32_Process | Select-Object ProcessId,ParentProcessId,Name | ConvertTo-Json -Compress"],
                       capture_output=True, text=True, encoding="utf-8")
    try:
        return {int(p["ProcessId"]): (int(p["ParentProcessId"]), p["Name"]) for p in json.loads(r.stdout)}
    except Exception:  # noqa: BLE001
        return {}


def descendants(root_pid: int, table: dict[int, tuple[int, str]]) -> dict[int, str]:
    out: dict[int, str] = {}
    todo = [root_pid]
    while todo:
        cur = todo.pop()
        for pid, (ppid, name) in table.items():
            if ppid == cur and pid not in out:
                out[pid] = name
                todo.append(pid)
    return out


# ---- 1 回の実行: サーバー × 提示 --------------------------------------------------------------------------------------
async def req(c: LspClient, method: str, params: Any, timeout: float = 30.0) -> Any:
    try:
        return await c.request(method, params, timeout=timeout)
    except LspError as e:
        return {"__error__": f"{e.error.get('code')}: {str(e.error.get('message'))[:80]}"}
    except TimeoutError:
        return {"__error__": "timeout"}


def is_err(x: Any) -> bool:
    return isinstance(x, dict) and "__error__" in x


def loc_ranges(res: Any) -> list[tuple[str | None, dict[str, Any]]]:
    """definition / references の結果から (uri, range) を取り出す（Location / LocationLink / 配列）。"""
    if not res or is_err(res):
        return []
    items = res if isinstance(res, list) else [res]
    out = []
    for it in items:
        if "targetUri" in it:
            out.append((it["targetUri"], it.get("targetSelectionRange") or it["targetRange"]))
        else:
            out.append((it.get("uri"), it["range"]))
    return out


async def run_one(srv: Srv, offer_label: str, offer: list[str] | None) -> dict[str, Any]:
    text = TEXTS[srv.lang]
    lines = text.split("\n")
    idx = LineIndex(text.encode("utf-8"))  # サーバーに送る本文そのものから作る（ディスクの読み直しではない）
    path = srv.root / srv.file
    rec: dict[str, Any] = {"server": srv.name, "offer": offer_label}
    c = LspClient(srv.name, srv.cmd, srv.root, config_provider=srv.config_provider, env=srv.env)
    tree_before: dict[int, str] = {}
    await c.start()
    try:
        init = await c.initialize(init_options=srv.init_options, encodings=offer, timeout=srv.ready_timeout_s)
        caps = init.get("capabilities", {})
        rec["serverInfo"] = init.get("serverInfo")
        rec["positionEncoding"] = caps.get("positionEncoding", "<absent>")
        neg = caps.get("positionEncoding", "utf-16")
        unit = neg if neg in UNITS else "utf-16"
        rec["unit_used_by_client"] = unit
        uri = c.did_open(path, srv.language_id, text=text)
        bad_line, bad_cp = next((i, ln.index(BAD_TOKEN[srv.lang])) for i, ln in enumerate(lines) if BAD_TOKEN[srv.lang] in ln)
        n = await c.wait_for("textDocument/publishDiagnostics",
                             lambda p: norm_uri(p["uri"]) == norm_uri(uri) and any(
                                 d["range"]["start"]["line"] == bad_line for d in p["diagnostics"]),
                             timeout=srv.ready_timeout_s)
        await asyncio.sleep(1.0)
        rec["diag_arrived"] = n is not None
        tdi = {"uri": uri}

        def have(*keys: str) -> bool:
            return any(caps.get(k) for k in keys)

        # ---- 診断（push）: 範囲を各単位で読んで bad_token になる単位 ----
        diags = [d for nn in c.diag_for(path) for d in nn.params["diagnostics"]]
        d_obs = []
        for d in diags:
            tok = BAD_TOKEN[srv.lang] if d["range"]["start"]["line"] == bad_line else None
            if srv.name == "ruff" and tok is None and 'f"あ"' in lines[d["range"]["start"]["line"]]:
                tok = 'f"あ"'
            if tok is None:
                continue
            ln = d["range"]["start"]["line"]
            want = lines[ln].index(tok)
            d_obs.append({"msg": str(d.get("message"))[:50], "code": d.get("code"), "start": d["range"]["start"]["character"],
                          "end": d["range"]["end"]["character"], "token": tok,
                          "units": units_decoding(lines, d["range"], tok),
                          "li": lineindex_check(idx, ln, d["range"]["start"]["character"], unit, want)})
        rec["diagnostics"] = d_obs

        # ---- ruff: codeAction（F541 の修正の編集範囲）----
        if srv.name == "ruff":
            ln = next(i for i, s in enumerate(lines) if 'f"あ"' in s)
            cp0 = lines[ln].index('f"あ"')
            ca: dict[str, Any] = {}
            for su in UNITS:
                a, b = col_in(lines[ln], cp0, su), col_in(lines[ln], cp0 + 4, su)
                r = await req(c, "textDocument/codeAction", {"textDocument": tdi, "context": {"diagnostics": []},
                                                              "range": {"start": {"line": ln, "character": a},
                                                                        "end": {"line": ln, "character": b}}})
                acts = [] if not r or is_err(r) else r
                edits = []
                for ac in acts:
                    for e in (ac.get("edit", {}).get("changes", {}) or {}).values():
                        edits += e
                    for dc in ac.get("edit", {}).get("documentChanges", []) or []:
                        edits += dc.get("edits", [])
                ca[su] = {"sent": [a, b], "n_actions": len(acts), "titles": [x.get("title") for x in acts][:3],
                          "edit_units": [units_decoding(lines, e["range"], "f") for e in edits][:3],
                          "edit_chars": [(e["range"]["start"]["character"], e["range"]["end"]["character"]) for e in edits][:3]}
            rec["codeAction_by_sent_unit"] = ca

        # ---- hover / definition / references / rename（対応するサーバーのみ）----
        cases = []
        for ident in CASES[srv.lang]:
            occ = find_occurrences(lines, ident)
            if len(occ) < 2:
                continue
            (dl, dc), (ul, uc) = occ[0], occ[1]
            cs: dict[str, Any] = {"ident": ident, "def": [dl, dc], "use": [ul, uc]}
            sent_def = idx.to_unit(Position(dl, dc), to_unit_enum(unit)).value
            sent_use = idx.to_unit(Position(ul, uc), to_unit_enum(unit)).value
            assert sent_def[1] == col_in(lines[dl], dc, unit) and sent_use[1] == col_in(lines[ul], uc, unit)
            cs["expected_cols"] = {u: [col_in(lines[dl], dc, u), col_in(lines[ul], uc, u)] for u in UNITS}

            def pos(line: int, col: int) -> dict[str, Any]:
                return {"textDocument": tdi, "position": {"line": line, "character": col}}

            if have("hoverProvider"):
                h = await req(c, "textDocument/hover", pos(dl, sent_def[1]))
                rng = h.get("range") if isinstance(h, dict) and not is_err(h) else None
                cs["hover"] = {"null": h is None, "err": h.get("__error__") if is_err(h) else None, "range": rng,
                               "units": units_decoding(lines, rng, ident) if rng else None,
                               "li": lineindex_check(idx, dl, rng["start"]["character"], unit, dc) if rng else None}
            if have("definitionProvider"):
                d = await req(c, "textDocument/definition", pos(ul, sent_use[1]))
                lr = loc_ranges(d)
                cs["definition"] = {"n": len(lr), "err": d.get("__error__") if is_err(d) else None,
                                    "start_char": lr[0][1]["start"]["character"] if lr else None,
                                    "line_ok": bool(lr) and lr[0][1]["start"]["line"] == dl,
                                    "units": units_decoding(lines, lr[0][1], ident) if lr else None,
                                    "li": lineindex_check(idx, dl, lr[0][1]["start"]["character"], unit, dc) if lr else None}
            if have("referencesProvider"):
                r = await req(c, "textDocument/references",
                              {**pos(dl, sent_def[1]), "context": {"includeDeclaration": True}})
                lr = loc_ranges(r)
                want = {(dl, dc), (ul, uc)}
                got = []
                for _, rg in lr:
                    ln = rg["start"]["line"]
                    cp_want = next((w[1] for w in want if w[0] == ln), None)
                    got.append({"line": ln, "chars": [rg["start"]["character"], rg["end"]["character"]],
                                "units": units_decoding(lines, rg, ident),
                                "li": lineindex_check(idx, ln, rg["start"]["character"], unit, cp_want) if cp_want is not None else None})
                cs["references"] = {"n": len(lr), "err": r.get("__error__") if is_err(r) else None, "items": got}
            if have("renameProvider"):
                new = ident + "_r" if ident.isascii() else "別名"
                rn = await req(c, "textDocument/rename", {**pos(dl, sent_def[1]), "newName": new})
                edits = []
                if rn and not is_err(rn):
                    for u2, es in (rn.get("changes") or {}).items():
                        if norm_uri(u2) == norm_uri(uri):
                            edits += es
                    for dcg in rn.get("documentChanges") or []:
                        if "edits" in dcg and norm_uri(dcg["textDocument"]["uri"]) == norm_uri(uri):
                            edits += dcg["edits"]
                expect = re.sub(rf"(?<!\w){re.escape(ident)}(?!\w)", new, text)
                ok_units = []
                for u in UNITS:
                    try:
                        if apply_text_edits(text, edits, u) == expect:
                            ok_units.append(u)
                    except ValueError:
                        pass
                cs["rename"] = {"n_edits": len(edits), "err": rn.get("__error__") if is_err(rn) else None,
                                "chars": [(e["range"]["start"]["character"], e["range"]["end"]["character"]) for e in edits],
                                "units_reproducing_expected_text": ok_units,
                                "li_apply_ok": None}
                if edits:  # LineIndex でバイト列へ適用: 後ろの編集から。受信は from_unit、書き込みはバイトオフセット
                    data = bytearray(text.encode("utf-8"))
                    for e in sorted(edits, key=lambda e: (e["range"]["start"]["line"], e["range"]["start"]["character"]), reverse=True):
                        s0 = idx.position_to_offset(idx.from_unit(e["range"]["start"]["line"], e["range"]["start"]["character"], to_unit_enum(unit)).value).value
                        e0 = idx.position_to_offset(idx.from_unit(e["range"]["end"]["line"], e["range"]["end"]["character"], to_unit_enum(unit)).value).value
                        data[s0:e0] = e["newText"].encode("utf-8")
                    cs["rename"]["li_apply_ok"] = bytes(data).decode("utf-8", "replace") == expect
            # ---- 送る側の単位違い: 各単位の列で hover(定義位置) と definition(使用位置) ----
            if have("hoverProvider", "definitionProvider"):
                mis: dict[str, Any] = {}
                for su in UNITS:
                    ent: dict[str, Any] = {}
                    if have("hoverProvider"):
                        h = await req(c, "textDocument/hover", pos(dl, col_in(lines[dl], dc, su)))
                        if is_err(h):
                            ent["hover"] = h["__error__"]
                        elif not h:
                            ent["hover"] = "null"
                        else:
                            rg = h.get("range")
                            dec = decode_range(lines, rg, unit) if rg else None
                            ent["hover"] = "hit" if dec == ident and rg["start"]["line"] == dl else f"other:{dec!r}"
                    if have("definitionProvider"):
                        d = await req(c, "textDocument/definition", pos(ul, col_in(lines[ul], uc, su)))
                        lr = loc_ranges(d)
                        if is_err(d):
                            ent["definition"] = d["__error__"]
                        elif not lr:
                            ent["definition"] = "empty"
                        else:
                            dec = decode_range(lines, lr[0][1], unit)
                            ent["definition"] = "hit" if dec == ident and lr[0][1]["start"]["line"] == dl else f"other:{dec!r}@L{lr[0][1]['start']['line']}"
                    mis[su] = ent
                cs["sent_unit_matrix"] = mis
            cases.append(cs)
        rec["cases"] = cases

        # ---- サロゲートペアの途中を指す列（UTF-16 で 😀 の 2 つ目のユニット）----
        mid: dict[str, Any] = {}
        if have("hoverProvider"):
            ln = next(i for i, s in enumerate(lines) if s.startswith(("u_astral", "export const uAstral", "pub const U_ASTRAL")))
            cp0 = lines[ln].index(EMO)
            for label, col in (("utf16_mid_pair", col_in(lines[ln], cp0, "utf-16") + 1),
                               ("utf8_mid_char", col_in(lines[ln], cp0, "utf-8") + 1)):
                h = await req(c, "textDocument/hover", {"textDocument": tdi, "position": {"line": ln, "character": col}})
                mid[label] = {"col": col, "result": h["__error__"] if is_err(h) else ("null" if not h else "non-null"),
                              "range": h.get("range") if isinstance(h, dict) and not is_err(h) else None}
        rec["mid_char"] = mid

        # ---- 終了前にプロセス木を記録 → shutdown → exit → 孤児確認 ----
        if c.proc is not None:
            tree_before = descendants(c.proc.pid, process_table())
    finally:
        rec["shutdown"] = await c.shutdown(grace_s=8.0)
    if tree_before:
        await asyncio.sleep(1.5)
        after = process_table()
        rec["child_procs"] = {str(p): n for p, n in tree_before.items()}
        rec["orphans_after_shutdown"] = {str(p): n for p, n in tree_before.items() if p in after}
        for p in list(rec["orphans_after_shutdown"]):  # 自分が起動した子孫だけを片付ける
            subprocess.run(["taskkill", "/F", "/T", "/PID", p], capture_output=True)
    rec["stderr_tail"] = [s for _, s in c.stderr_lines[-3:]]
    return rec


async def run_server(srv: Srv) -> list[dict[str, Any]]:
    out = []
    for label, offer in OFFERS:
        try:
            out.append(await run_one(srv, label, offer))
        except Exception as e:  # noqa: BLE001
            out.append({"server": srv.name, "offer": label, "fatal": repr(e)})
    return out


# ---- LineIndex 単体の網羅検査 ------------------------------------------------------------------------------------------
def lineindex_selftest() -> dict[str, Any]:
    extra = ["a", "", "ASCII only", "あいう", EMO, f"x{EMO}y", f"{EMO}{EMO}{EMO}日本語", EACUTE, COMB, MIX,
             "\U0001F468‍\U0001F469‍\U0001F467 family", "\U0001F1EF\U0001F1F5 flag", "\U00020BB7野家", "tab\there"]
    samples = list(dict.fromkeys(PY_TEXT.split("\n") + TS_TEXT.split("\n") + extra))
    res = {"lines": len(samples), "cp_positions": 0, "conv_mismatch": [], "mid_char_not_clamped": [], "eol_overrun_not_clamped": []}
    for s in samples:
        idx = LineIndex(s.encode("utf-8"))
        for cp in range(len(s) + 1):
            col = {u: col_in(s, cp, u) for u in UNITS}
            res["cp_positions"] += 1
            for su in UNITS:
                for du in UNITS:
                    r = idx.convert_col(0, col[su], Unit(su), Unit(du))
                    if r.value != col[du] or r.clamped:
                        res["conv_mismatch"].append((s, cp, su, du, r.value, col[du], r.clamped))
        # 文字の途中（utf-8 の継続バイト、サロゲートペアの 2 つ目）は直前の境界へ丸めて clamped
        for su in ("utf-8", "utf-16"):
            valid = {col_in(s, cp, su) for cp in range(len(s) + 1)}
            for c0 in range(col_in(s, len(s), su) + 1):
                if c0 not in valid:
                    r = idx.convert_col(0, c0, Unit(su), Unit.CODEPOINT)
                    if not r.clamped:
                        res["mid_char_not_clamped"].append((s, su, c0))
        end16 = col_in(s, len(s), "utf-16")
        if not idx.convert_col(0, end16 + 3, Unit.UTF16, Unit.CODEPOINT).clamped:
            res["eol_overrun_not_clamped"].append(s)
    # 改行・BOM を含む本文全体: バイトオフセット ↔ Position の往復と LSP 列（UTF-16）
    for label, data in (("lf", PY_TEXT.encode()), ("crlf", PY_TEXT.replace("\n", "\r\n").encode()),
                        ("bom+crlf", b"\xef\xbb\xbf" + PY_TEXT.replace("\n", "\r\n").encode())):
        idx = LineIndex(data)
        bad = 0
        n = 0
        for line in range(idx.line_count):
            text = idx.line_text(line)
            for cp in range(len(text) + 1):
                off = idx.position_to_offset(Position(line, cp)).value
                back = idx.offset_to_position(off).value
                u16 = idx.to_unit(Position(line, cp), Unit.UTF16).value[1]
                n += 1
                if back != Position(line, cp) or u16 != col_in(text, cp, "utf-16"):
                    bad += 1
        res[f"offset_roundtrip_{label}"] = {"checked": n, "bad": bad}
    res["ok"] = not (res["conv_mismatch"] or res["mid_char_not_clamped"] or res["eol_overrun_not_clamped"]) and all(
        v["bad"] == 0 for k, v in res.items() if k.startswith("offset_roundtrip_"))
    return res


# ---- 表 ------------------------------------------------------------------------------------------------------------
def inter(sets: list[list[str]]) -> str:
    sets = [s for s in sets if s is not None]
    if not sets:
        return "-"
    cur = set(sets[0])
    for s in sets[1:]:
        cur &= set(s)
    return "|".join(u for u in UNITS if u in cur) or "なし"


def summarize(rec: dict[str, Any]) -> dict[str, Any]:
    if "fatal" in rec:
        return {"server": rec["server"], "offer": rec["offer"], "fatal": rec["fatal"]}
    cs = rec.get("cases", [])
    li_recv = [x["li"]["recv_ok"] for c in cs for x in [c.get("hover"), c.get("definition")] if x and x.get("li")]
    li_recv += [i["li"]["recv_ok"] for c in cs for i in (c.get("references") or {}).get("items", []) if i.get("li")]
    li_recv += [d["li"]["recv_ok"] for d in rec.get("diagnostics", [])]
    li_send = [x["li"]["send_ok"] for c in cs for x in [c.get("hover"), c.get("definition")] if x and x.get("li")]
    li_send += [d["li"]["send_ok"] for d in rec.get("diagnostics", [])]
    return {
        "server": rec["server"], "offer": rec["offer"], "negotiated": rec["positionEncoding"],
        "hover": inter([c["hover"]["units"] or [] for c in cs if c.get("hover")]) if any(c.get("hover") for c in cs) else "-",
        "definition": inter([c["definition"]["units"] or [] for c in cs if c.get("definition")]) if any(c.get("definition") for c in cs) else "-",
        "references": inter([i["units"] for c in cs for i in (c.get("references") or {}).get("items", [])]) if any(c.get("references") for c in cs) else "-",
        "rename": inter([c["rename"]["units_reproducing_expected_text"] for c in cs if c.get("rename")]) if any(c.get("rename") for c in cs) else "-",
        "diag": inter([d["units"] for d in rec.get("diagnostics", [])]),
        "li_recv": f"{sum(li_recv)}/{len(li_recv)}", "li_send": f"{sum(li_send)}/{len(li_send)}",
        "li_apply": f"{sum(1 for c in cs if (c.get('rename') or {}).get('li_apply_ok'))}/{sum(1 for c in cs if c.get('rename'))}",
        "orphans": list((rec.get("orphans_after_shutdown") or {}).values()),
        "exit": (rec.get("shutdown") or {}).get("exit_code"),
    }


